#!/bin/bash
# generate-claude-docs.sh — Generates architecture documentation in docs/claude/
# Run manually or via pre-commit hook when Swift/Package.swift files change.

set -uo pipefail

ROOT_DIR="$(cd "$(dirname "$0")/.." && pwd)"
DOCS_DIR="$ROOT_DIR/docs/claude"
PACKAGES_DIR="$ROOT_DIR/LocalPackages"

mkdir -p "$DOCS_DIR/packages" "$DOCS_DIR/extensions"

# ─── Helpers ────────────────────────────────────────────────────────────────

extract_public_types() {
    local src_dir="$1"
    local kind="$2" # protocol|class|struct|enum|actor
    if [ -d "$src_dir" ]; then
        grep -rn "^public \(final \)\{0,1\}${kind} " "$src_dir" 2>/dev/null \
            | grep -v "Tests/" \
            | grep -v "FfiConverter" \
            | sed "s|${ROOT_DIR}/||" \
            | while IFS=: read -r file line content; do
                local name
                name=$(echo "$content" | sed "s/^public \(final \)\{0,1\}${kind} //" | sed 's/[:{<[:space:]].*//' | tr -d ' ')
                if [ -n "$name" ]; then
                    echo "- \`${name}\` — \`${file}:${line}\`"
                fi
            done | sort -u
    fi
}

extract_local_deps() {
    local pkg_file="$1"
    grep '.package(name:' "$pkg_file" 2>/dev/null \
        | sed 's/.*name: *"//' | sed 's/".*//' \
        | sort -u
}

extract_external_deps() {
    local pkg_file="$1"
    grep '.package(url:' "$pkg_file" 2>/dev/null \
        | sed 's|.*github.com/[^/]*/||' | sed 's|".*||' | sed 's|\.git$||' \
        | sort -u
}

count_swift_files() {
    local dir="$1"
    find "$dir" -name "*.swift" -not -path "*/Tests/*" 2>/dev/null | wc -l | tr -d ' '
}

list_subdirs() {
    local dir="$1"
    if [ -d "$dir" ]; then
        find "$dir" -mindepth 1 -maxdepth 1 -type d -not -name "Tests" -not -name "Resources" \
            | sort | while read -r d; do
            echo "- \`$(basename "$d")/\`"
        done
    fi
}

get_swift_tools_version() {
    local pkg_file="$1"
    head -1 "$pkg_file" 2>/dev/null | sed 's|.*swift-tools-version: *||'
}

has_test_target() {
    local pkg_file="$1"
    grep -q "testTarget" "$pkg_file" 2>/dev/null && echo "yes" || echo "no"
}

get_test_target_name() {
    local pkg_file="$1"
    # Join lines, extract testTarget block, get first name: value
    tr -d '\n' < "$pkg_file" 2>/dev/null \
        | grep -o '\.testTarget([^)]*' \
        | head -1 \
        | sed 's/.*\.testTarget( *//' \
        | grep -o 'name: *"[^"]*"' \
        | head -1 | sed 's/name: *"//' | sed 's/"//'
}

# ─── Package Doc Generator ──────────────────────────────────────────────────

generate_package_doc() {
    local pkg_name="$1"
    local pkg_dir="$PACKAGES_DIR/$pkg_name"
    local pkg_file="$pkg_dir/Package.swift"
    local src_dir="$pkg_dir/Sources"
    local out_file="$DOCS_DIR/packages/$(echo "$pkg_name" | tr '[:upper:]' '[:lower:]' | tr ' ' '-').md"

    if [ ! -f "$pkg_file" ]; then
        return
    fi

    local swift_version
    swift_version=$(get_swift_tools_version "$pkg_file")
    local file_count
    file_count=$(count_swift_files "$src_dir")
    local test_target
    test_target=$(get_test_target_name "$pkg_file")

    {
        echo "# $pkg_name"
        echo ""
        echo "> Auto-generated by \`scripts/generate-claude-docs.sh\` — do not edit manually."
        echo ""
        echo "**Swift Tools Version:** $swift_version"
        echo "**Source files:** $file_count"
        if [ -n "$test_target" ]; then
            echo "**Test target:** \`$test_target\`"
        fi
        echo ""

        # Local dependencies
        local local_deps
        local_deps=$(extract_local_deps "$pkg_file")
        if [ -n "$local_deps" ]; then
            echo "## Local Dependencies"
            echo ""
            echo "$local_deps" | while read -r dep; do
                echo "- $dep"
            done
            echo ""
        else
            echo "## Local Dependencies"
            echo ""
            echo "None (foundation layer)"
            echo ""
        fi

        # External dependencies
        local external_deps
        external_deps=$(extract_external_deps "$pkg_file")
        if [ -n "$external_deps" ]; then
            echo "## External Dependencies"
            echo ""
            echo "$external_deps" | while read -r dep; do
                echo "- $dep"
            done
            echo ""
        fi

        # Source structure
        local source_target_dir
        source_target_dir=$(find "$src_dir" -mindepth 1 -maxdepth 1 -type d 2>/dev/null | head -1)
        if [ -n "$source_target_dir" ] && [ -d "$source_target_dir" ]; then
            local subdirs
            subdirs=$(find "$source_target_dir" -mindepth 1 -maxdepth 1 -type d -not -name "Resources" | sort)
            if [ -n "$subdirs" ]; then
                echo "## Source Structure"
                echo ""
                echo "$subdirs" | while read -r d; do
                    local dirname
                    dirname=$(basename "$d")
                    local subfile_count
                    subfile_count=$(find "$d" -name "*.swift" | wc -l | tr -d ' ')
                    echo "- \`${dirname}/\` ($subfile_count files)"
                done
                echo ""
            fi
        fi

        # Public types
        echo "## Public API"
        echo ""

        for kind in protocol actor class struct enum; do
            local types
            types=$(extract_public_types "$src_dir" "$kind")
            if [ -n "$types" ]; then
                local kind_plural
                case "$kind" in
                    class) kind_plural="Classes" ;;
                    *) kind_plural="$(echo "$kind" | awk '{print toupper(substr($0,1,1)) substr($0,2)}')s" ;;
                esac
                echo "### ${kind_plural}"
                echo ""
                echo "$types"
                echo ""
            fi
        done

        # Swift settings
        if grep -q "enableUpcomingFeature" "$pkg_file" 2>/dev/null; then
            echo "## Swift Feature Flags"
            echo ""
            grep "enableUpcomingFeature" "$pkg_file" | sed 's/.*enableUpcomingFeature("/- /' | sed 's/").*//'
            echo ""
        fi

        if grep -q "defaultIsolation" "$pkg_file" 2>/dev/null; then
            echo "## Default Isolation"
            echo ""
            grep "defaultIsolation" "$pkg_file" | sed 's/.*defaultIsolation(/- /' | sed 's/).*//'
            echo ""
        fi

    } > "$out_file"
}

# ─── Extension Doc Generator ────────────────────────────────────────────────

generate_extension_doc() {
    local ext_name="$1"
    local ext_dir="$2"
    local out_file="$DOCS_DIR/extensions/$(echo "$ext_name" | tr '[:upper:]' '[:lower:]' | tr ' ' '-').md"

    if [ ! -d "$ext_dir" ]; then
        return
    fi

    local file_count
    file_count=$(find "$ext_dir" -name "*.swift" 2>/dev/null | wc -l | tr -d ' ')

    {
        echo "# $ext_name"
        echo ""
        echo "> Auto-generated by \`scripts/generate-claude-docs.sh\` — do not edit manually."
        echo ""
        echo "**Path:** \`$(echo "$ext_dir" | sed "s|${ROOT_DIR}/||")/\`"
        echo "**Swift files:** $file_count"
        echo ""

        echo "## Files"
        echo ""
        find "$ext_dir" -name "*.swift" -type f | sort | while read -r f; do
            local rel
            rel=$(echo "$f" | sed "s|${ROOT_DIR}/||")
            local basename
            basename=$(basename "$f")
            echo "- \`${basename}\` — \`${rel}\`"
        done
        echo ""

        # Key types
        local types=""
        for kind in protocol actor class struct enum; do
            local found
            found=$(grep -rn "^\(public \)\{0,1\}\(final \)\{0,1\}${kind} " "$ext_dir" --include="*.swift" 2>/dev/null \
                | sed "s|${ROOT_DIR}/||" \
                | while IFS=: read -r file line content; do
                    local name
                    name=$(echo "$content" | sed "s/^\(public \)\{0,1\}\(final \)\{0,1\}${kind} //" | sed 's/[:{<[:space:]].*//' | tr -d ' ')
                    if [ -n "$name" ]; then
                        echo "- \`${name}\` (${kind}) — \`${file}:${line}\`"
                    fi
                done)
            if [ -n "$found" ]; then
                types="${types}${found}\n"
            fi
        done
        if [ -n "$types" ]; then
            echo "## Key Types"
            echo ""
            echo -e "$types"
        fi

    } > "$out_file"
}

# ─── DI Containers Doc ──────────────────────────────────────────────────────

generate_di_doc() {
    local di_dir="$PACKAGES_DIR/PresentationLayer/Sources/PresentationLayer/DI+Implementation"
    local out_file="$DOCS_DIR/di-containers.md"

    {
        echo "# Dependency Injection Containers"
        echo ""
        echo "> Auto-generated by \`scripts/generate-claude-docs.sh\` — do not edit manually."
        echo ""
        echo "Uses [Factory](https://github.com/hmlongco/Factory) (FactoryKit). All containers use singleton scope."
        echo "Inject with: \`@LazyInjected(\\\\ContainerName.property)\`"
        echo ""

        for container_file in "$di_dir"/*Container.swift; do
            if [ ! -f "$container_file" ]; then continue; fi

            local container_name
            container_name=$(basename "$container_file" .swift)
            echo "## $container_name"
            echo ""

            # Extract registrations (var name: Factory<Type>)
            grep -n "var .*: Factory<" "$container_file" 2>/dev/null | while IFS=: read -r line content; do
                local name
                name=$(echo "$content" | sed 's/.*var //' | sed 's/:.*//' | tr -d ' ')
                local type
                type=$(echo "$content" | sed 's/.*Factory<//' | sed 's/>.*//')
                echo "- \`${name}\` → \`${type}\`"
            done
            echo ""
        done

    } > "$out_file"
}

# ─── Architecture Overview ──────────────────────────────────────────────────

generate_architecture_overview() {
    local out_file="$DOCS_DIR/architecture-overview.md"

    {
        echo "# Architecture Overview"
        echo ""
        echo "> Auto-generated by \`scripts/generate-claude-docs.sh\` — do not edit manually."
        echo ""
        echo "## Layer Dependency Graph"
        echo ""
        echo "\`\`\`"
        echo "PresentationLayer"
        echo "  ├── DomainLayer"
        echo "  │     ├── DataLayer"
        echo "  │     │     ├── Models"
        echo "  │     │     ├── CommonUtilities → Models"
        echo "  │     │     ├── AuthenticatorRustCore"
        echo "  │     │     └── Macro"
        echo "  │     ├── AuthenticatorRustCore"
        echo "  │     └── CommonUtilities"
        echo "  ├── DataLayer"
        echo "  ├── Models"
        echo "  ├── CommonUtilities"
        echo "  └── Macro"
        echo "\`\`\`"
        echo ""
        echo "**Dependency flow is strictly top-down.** No package may import a package above it."
        echo ""
        echo "## Package Summary"
        echo ""
        echo "| Package | Swift Tools | Files | Local Deps | Role |"
        echo "|---------|-------------|-------|------------|------|"

        for pkg_dir in "$PACKAGES_DIR"/*/; do
            local pkg_name
            pkg_name=$(basename "$pkg_dir")
            local pkg_file="$pkg_dir/Package.swift"
            if [ ! -f "$pkg_file" ]; then continue; fi

            local swift_version
            swift_version=$(get_swift_tools_version "$pkg_file")
            local src_dir="$pkg_dir/Sources"
            local file_count
            file_count=$(count_swift_files "$src_dir")
            local local_deps
            local_deps=$(extract_local_deps "$pkg_file" | tr '\n' ',' | sed 's/,$//' | sed 's/,/, /g')
            [ -z "$local_deps" ] && local_deps="—"

            local role=""
            case "$pkg_name" in
                Models) role="Pure value types, SwiftData entities" ;;
                CommonUtilities) role="Shared extensions, constants" ;;
                AuthenticatorRustCore) role="Rust FFI — TOTP/encryption" ;;
                DataLayer) role="Repositories, services, networking" ;;
                DomainLayer) role="Use cases, business logic" ;;
                PresentationLayer) role="SwiftUI views, ViewModels, DI" ;;
                Macro) role="Swift compiler macros" ;;
                *) role="—" ;;
            esac

            echo "| $pkg_name | $swift_version | $file_count | $local_deps | $role |"
        done

        echo ""
        echo "## App Targets"
        echo ""
        echo "| Target | Path | Platform | Description |"
        echo "|--------|------|----------|-------------|"
        echo "| Authenticator | \`Authenticator/\` | iOS 18+ | Main app |"
        echo "| AuthenticatorTests | \`AuthenticatorTests/\` | iOS | Unit tests (Swift Testing) |"
        echo "| AuthenticatorUITests | \`AuthenticatorUITests/\` | iOS | UI tests (XCTest) |"
        echo "| Autofill | \`Autofill/\` | iOS | Credential provider extension |"
        echo "| AutofillMacos | \`AutofillMacos/\` | macOS | Credential provider extension |"
        echo "| WatchAuthenticator Watch App | \`WatchAuthenticator Watch App/\` | watchOS | Watch companion app |"
        echo "| Watch Widget | \`Watch Widget/\` | watchOS | Complications/widgets |"
        echo ""
        echo "## Key Patterns"
        echo ""
        echo "- **MVVM + Clean Architecture** — ViewModels are \`@Observable @MainActor\` classes"
        echo "- **Protocol-first** — protocols in DomainLayer, implementations in DataLayer"
        echo "- **Factory DI** — \`@LazyInjected\` for dependency injection (4 containers)"
        echo "- **Actor-based repository** — \`EntryRepository\` is an actor for thread-safe CRUD"
        echo "- **Swift 6 concurrency** — \`async/await\`, \`Sendable\`, \`@MainActor\` throughout"
        echo "- **SwiftData + Keychain** — local persistence with encrypted secrets"
        echo "- **Proton API** — remote sync, encryption, key management"
        echo ""
        echo "## Concurrency Settings"
        echo ""
        echo "Active Swift feature flags (in Package.swift):"
        echo "- \`NonisolatedNonsendingByDefault\` — DataLayer, DomainLayer, PresentationLayer"
        echo "- \`InferIsolatedConformances\` — DataLayer, DomainLayer, PresentationLayer"
        echo "- \`defaultIsolation(MainActor.self)\` — PresentationLayer only"
        echo ""

    } > "$out_file"
}

# ─── README Index ────────────────────────────────────────────────────────────

generate_readme() {
    local out_file="$DOCS_DIR/README.md"
    local timestamp
    timestamp=$(date -u "+%Y-%m-%d %H:%M UTC")

    {
        echo "# Claude Documentation Index"
        echo ""
        echo "> Auto-generated by \`scripts/generate-claude-docs.sh\` — do not edit manually."
        echo "> Last updated: $timestamp"
        echo ""
        echo "Architecture and package documentation for Proton Authenticator."
        echo "Regenerate with: \`./scripts/generate-claude-docs.sh\`"
        echo ""
        echo "## Overview"
        echo ""
        echo "- [Architecture Overview](architecture-overview.md) — layer graph, package summary, key patterns"
        echo "- [DI Containers](di-containers.md) — all Factory registrations"
        echo ""
        echo "## Local Packages"
        echo ""

        for doc in "$DOCS_DIR"/packages/*.md; do
            if [ ! -f "$doc" ]; then continue; fi
            local name
            name=$(head -1 "$doc" | sed 's/# //')
            local rel
            rel=$(basename "$doc")
            echo "- [$name](packages/$rel)"
        done

        echo ""
        echo "## Extensions & Targets"
        echo ""

        for doc in "$DOCS_DIR"/extensions/*.md; do
            if [ ! -f "$doc" ]; then continue; fi
            local name
            name=$(head -1 "$doc" | sed 's/# //')
            local rel
            rel=$(basename "$doc")
            echo "- [$name](extensions/$rel)"
        done

        echo ""

    } > "$out_file"
}

# ─── Main ────────────────────────────────────────────────────────────────────

echo "Generating Claude docs in $DOCS_DIR ..."

# Generate package docs
for pkg_dir in "$PACKAGES_DIR"/*/; do
    pkg_name=$(basename "$pkg_dir")
    echo "  Package: $pkg_name"
    generate_package_doc "$pkg_name"
done

# Generate extension/target docs
echo "  Extension: Autofill"
generate_extension_doc "Autofill" "$ROOT_DIR/Autofill"

echo "  Extension: AutofillMacos"
generate_extension_doc "AutofillMacos" "$ROOT_DIR/AutofillMacos"

echo "  Extension: WatchAuthenticator Watch App"
generate_extension_doc "WatchAuthenticator Watch App" "$ROOT_DIR/WatchAuthenticator Watch App"

echo "  Extension: Watch Widget"
generate_extension_doc "Watch Widget" "$ROOT_DIR/Watch Widget"

echo "  Extension: Authenticator (main app)"
generate_extension_doc "Authenticator" "$ROOT_DIR/Authenticator"

# Generate DI containers doc
echo "  DI Containers"
generate_di_doc

# Generate architecture overview
echo "  Architecture Overview"
generate_architecture_overview

# Generate README index
echo "  README index"
generate_readme

echo "Done. Docs written to docs/claude/"
